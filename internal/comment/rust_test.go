// TestRunRustは、Rustのコメントとdocコメントの違反と、検査から外す範囲を、CLIの診断位置・件数まで含めて確認する。
func TestRunRust(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want []string
	}{
		{name: "行コメントの本文", src: "// 最大 20 文字\nfn f() {}\n", want: []string{"1: §3.2"}},
		{name: "行末コメントの本文", src: "fn f() {\n    let x = 1; // 最大 20 文字\n}\n", want: []string{"2: §3.2"}},
		{name: "docコメントの本文", src: "/// 最大 20 文字（入力）\nfn f() {}\n", want: []string{"1: §3.1", "1: §3.2"}},
		{name: "モジュールのdocコメントの本文", src: "//! 最大 20 文字\n", want: []string{"1: §3.2"}},
		{name: "ブロックコメントの行番号", src: "/*\n正常\n最大 20 文字\n*/\nfn f() {}\n", want: []string{"3: §3.2"}},
		{name: "docのブロックコメントの本文", src: "/**\n * 最大 20 文字\n */\nfn f() {}\n", want: []string{"2: §3.2"}},
		{name: "モジュールのブロックdocコメントの本文", src: "/*! 最大 20 文字 */\n", want: []string{"1: §3.2"}},
		{name: "空のブロックコメント", src: "/**/\nfn f() {}\n"},
		{name: "入れ子のブロックコメント", src: "/* 外側 /* 最大 20 文字 */ 外側 */\nfn f() {}\n", want: []string{"1: §3.2"}},
		{name: "違反の無いコメント", src: "/// 最大20文字 (入力) まで受け付ける。\nfn f() {}\n"},
		{name: "コメント内のインラインコード", src: "/// 例は `最大 20 文字（入力）`\nfn f() {}\n"},
		{name: "docコメントのコード例", src: "/// 例:\n///\n/// ```\n/// let label = \"最大 20 文字\"; // 最大 20 文字\n/// ```\nfn f() {}\n"},
		{name: "コード例の後ろの本文", src: "/// ```\n/// let x = 1;\n/// ```\n/// 最大 20 文字\nfn f() {}\n", want: []string{"4: §3.2"}},
		{name: "docコメントの共通の字下げは本文", src: "///  最大 20 文字\npub fn f() {}\n", want: []string{"1: §3.2"}},
		{name: "docコメントの浅い字下げも本文", src: "/// 本文。\n///   最大 20 文字\npub fn f() {}\n", want: []string{"2: §3.2"}},
		{name: "docコメントの字下げしたコード例", src: "/// コードの例。\n///\n///     let label = \"最大 20 文字\";\npub fn f() {}\n"},
		{name: "リスト内の字下げしたコード例", src: "/// - コードの例。\n///\n///       let label = \"最大 20 文字\";\npub fn f() {}\n"},
		{name: "リスト内のフェンスの後ろの本文", src: "/// - コードの例。\n///\n///   ```text\n///   最大 20 文字\n///   ```\n///   最大 30 文字\npub fn f() {}\n", want: []string{"6: §3.2"}},
		{name: "ブロックdocコメントの字下げしたコード例", src: "/**\n * コードの例。\n *\n *     let label = \"最大 20 文字\";\n */\npub fn f() {}\n"},
		{name: "ブロックdocコメントの共通の字下げは本文", src: "/**\n    最大 20 文字\n*/\npub fn f() {}\n", want: []string{"2: §3.2"}},
		{name: "docコメント内の複数行のインラインコード", src: "/// `最大 20 文字\n/// 最大 30 文字`\npub fn f() {}\n"},
		{name: "コードを挟む通常のコメントにはフェンスを引き継がない", src: "// ```text\nfn f() {} // 最大 20 文字\n", want: []string{"2: §3.2"}},
		{name: "行末のコメントは次の行のコメントにフェンスを引き継がない", src: "fn f() {\n    let x = 1; // ```text\n    // 最大 20 文字\n    let _ = x;\n}\n", want: []string{"3: §3.2"}},
		{name: "続く行のコメントはフェンスを引き継ぐ", src: "fn f() {\n    // ```text\n    // 最大 20 文字\n    // ```\n}\n"},
		{name: "行とブロックのdocコメントは同じ文書", src: "/// ```text\n/** 最大 20 文字 */\n/// ```\npub fn f() {}\n"},
		{name: "通常のコメントはdocコメントのコード例と分ける", src: "/// ```text\n// 最大 20 文字\n/// ```\npub fn f() {}\n", want: []string{"2: §3.2"}},
		{name: "空行を挟むdocコメントは同じ文書", src: "/// ```text\n\n/// 最大 20 文字\n/// ```\npub fn f() {}\n"},
		{name: "属性を挟むdocコメントは同じ文書", src: "/// ```text\n#[allow(dead_code)]\n/// 最大 20 文字\n/// ```\npub fn f() {}\n"},
		{name: "モジュールの外側と内側のdocコメントは同じ文書", src: "/// ```text\npub mod m {\n    //! 最大 20 文字\n    //! ```\n}\n"},
		{name: "別の項目のdocコメントにはフェンスを引き継がない", src: "/// ```text\npub fn f() {}\n/// 最大 20 文字\npub fn g() {}\n", want: []string{"3: §3.2"}},
		{name: "モジュールと項目のdocコメントは別の文書", src: "//! ```text\n/// 最大 20 文字\npub fn f() {}\n", want: []string{"2: §3.2"}},
		{name: "文字列リテラルは見ない", src: "fn f() -> &'static str {\n    \"コマンド nonoto を実行できなかった\"\n}\n"},
		{name: "文字列内のコメント記号", src: "fn f() -> &'static str {\n    \"// 最大 20 文字\"\n}\n"},
		{name: "raw文字列内のコメント記号", src: "fn f() -> &'static str {\n    r#\"/* 最大 20 文字 */\"#\n}\n"},
		{name: "文字リテラルとライフタイムの後ろのコメント", src: "fn f<'a>(_: &'a str) -> char {\n    '/' // 最大 20 文字\n}\n", want: []string{"2: §3.2"}},
		{name: "CRLFの行番号", src: "fn f() {}\r\n// 正常\r\n// 最大 20 文字\r\n", want: []string{"3: §3.2"}},
		{name: "生成物を除外", src: "// Code generated by tool. DO NOT EDIT.\n// 最大 20 文字\nfn f() {}\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			writeFile(t, dir, "sample.rs", tt.src)
			var stdout, stderr bytes.Buffer
			code := Run([]string{dir}, &stdout, &stderr)
			wantCode := 0
			wantStderr := ""
			if len(tt.want) > 0 {
				wantCode = 1
				wantStderr = fmt.Sprintf("\nkoryluslint comment: 日本語スタイル違反%d件\n", len(tt.want))
			}
			if code != wantCode || stderr.String() != wantStderr {
				t.Fatalf("終了コード = %d、期待値 = %d、標準エラー = %q、期待値 = %q", code, wantCode, stderr.String(), wantStderr)
			}
			var lines []string
			if stdout.Len() > 0 {
				lines = strings.Split(strings.TrimSpace(stdout.String()), "\n")
			}
			if len(lines) != len(tt.want) {
				t.Fatalf("診断数 = %d、期待値 = %d、標準出力 = %q", len(lines), len(tt.want), stdout.String())
			}
			for i, want := range tt.want {
				prefix := filepath.Join(dir, "sample.rs") + ":" + want + ":"
				if !strings.HasPrefix(lines[i], prefix) {
					t.Errorf("診断 = %q、期待する接頭辞 = %q", lines[i], prefix)
				}
			}
		})
	}
}

// TestRunRustSyntaxErrorは、構文エラーのあるRustのファイルを、ほかの形式の解析エラーと同じく通知して飛ばすことを確認する。
func TestRunRustSyntaxError(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeFile(t, dir, "sample.rs", "// 最大 20 文字\nfn f( {\n")
	var stdout, stderr bytes.Buffer
	if code := Run([]string{dir}, &stdout, &stderr); code != 0 {
		t.Fatalf("終了コード = %d、期待値 = 0", code)
	}
	if stdout.Len() != 0 || !strings.Contains(stderr.String(), "構文エラー") {
		t.Errorf("標準出力 = %q、標準エラー = %q、解析エラーだけの通知を期待", stdout.String(), stderr.String())
	}
}

// TestRunSkipsCargoTargetは、Cargoの出力先 (`target`) の下を走査しないことを確認する。
func TestRunSkipsCargoTarget(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	out := filepath.Join("target", "debug", "build")
	if err := os.MkdirAll(filepath.Join(dir, out), 0o750); err != nil {
		t.Fatalf("%sを作れなかった: %v", out, err)
	}
	writeFile(t, dir, filepath.Join(out, "out.rs"), "// 最大 20 文字\n")
	var stdout, stderr bytes.Buffer
	if code := Run([]string{dir}, &stdout, &stderr); code != 0 {
		t.Fatalf("終了コード = %d、期待値 = 0、標準出力 = %q", code, stdout.String())
	}
}
